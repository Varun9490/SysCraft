import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const wasmPath = resolve(
  root,
  "wasm/sim-kernel/target/wasm32-unknown-unknown/release/sim_kernel.wasm",
);
const outPath = resolve(root, "src/engine/wasm/simKernelBytes.ts");
const wasm = readFileSync(wasmPath);
const b64 = wasm.toString("base64");

mkdirSync(dirname(outPath), { recursive: true });
const source = `/* Generated by scripts/embed-sim-kernel.mjs. Do not edit by hand. */
export const SIM_KERNEL_WASM_BASE64 = ${JSON.stringify(b64)};
export const SIM_KERNEL_WASM_BYTES = ${wasm.length};
`;

writeFileSync(outPath, source);
console.log(`embedded ${wasm.length} bytes into src/engine/wasm/simKernelBytes.ts`);
